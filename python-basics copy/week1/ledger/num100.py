# 1. 生成 1-100 的列表
numbers = list(range(1, 101))
print(f"原始列表: {numbers}")

# 2. 取出所有偶数（切片）
# 索引从0开始，偶数在索引1, 3, 5... 即步长为2
even_numbers = numbers[1::2]  # 从索引1开始，步长2
print(f"偶数列表: {even_numbers}")

# 3. 反转列表
even_numbers.reverse()  # 原地反转
# 或者使用: even_numbers = even_numbers[::-1]
print(f"反转后的偶数列表: {even_numbers}")

# 4. 打印最大/最小/总和
print(f"最大值: {max(even_numbers)}")
print(f"最小值: {min(even_numbers)}")
print(f"总和: {sum(even_numbers)}")

