"""topk_test.py：同一问题，对比 k=3/5/10 的检索结果"""
import chromadb
import embed_utils as emb

client = chromadb.PersistentClient(path="./chroma_data")
col = client.get_or_create_collection(name="reports")

questions = [
    "本次被停牌的挂牌公司共有多少家",
    "停牌依据的是哪些具体条款",
    "名单中有哪些主办券商被涉及",
    "自2026年9月1日起被停牌的公司有哪些",
    "哪些公司由开源证券担任主办券商",
]

for q in questions:
    q_vec = emb.embed_texts([q])
    print(f"\n=== 问题：{q} ===")
    for k in (3, 5, 10):
        res = col.query(query_embeddings=q_vec, n_results=k)
        docs = res["documents"][0]
        print(f"k={k}: 返回 {len(docs)} 条，第一条前 60 字：")
        print("  ", docs[0][:60].replace("\n", " "))

