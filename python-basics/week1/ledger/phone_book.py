# 初始化联系人字典
contacts = {
    "张三": "13800138001",
    "李四": "13800138002",
    "王五": "13800138003"
}

# 菜单循环
while True:
    print("\n" + "=" * 40)
    print("        📱 通讯录管理系统")
    print("=" * 40)
    print("1. 查询号码")
    print("2. 添加联系人")
    print("3. 删除联系人")
    print("4. 显示全部联系人")
    print("5. 退出系统")
    print("=" * 40)
    
    choice = input("请选择操作 (1-5): ")
    
    # 1. 查询号码
    if choice == "1":
        name = input("请输入要查询的姓名: ")
        if name in contacts:
            print(f"{name} 的电话号码是: {contacts[name]}")
        else:
            print(f"❌ 未找到联系人: {name}")
    
    # 2. 添加联系人
    elif choice == "2":
        name = input("请输入联系人姓名: ")
        if name in contacts:
            print(f"⚠️ 联系人 {name} 已存在，电话号码为: {contacts[name]}")
            update = input("是否更新号码？(y/n): ").lower()
            if update == "y":
                phone = input("请输入新电话号码: ")
                contacts[name] = phone
                print(f"✅ 已更新 {name} 的电话号码")
        else:
            phone = input("请输入电话号码: ")
            contacts[name] = phone
            print(f"✅ 已添加联系人: {name} -> {phone}")
    
    # 3. 删除联系人
    elif choice == "3":
        name = input("请输入要删除的姓名: ")
        if name in contacts:
            confirm = input(f"确认删除 {name} 吗？(y/n): ").lower()
            if confirm == "y":
                del contacts[name]
                print(f"✅ 已删除联系人: {name}")
            else:
                print("已取消删除")
        else:
            print(f"❌ 未找到联系人: {name}")
    
    # 4. 显示全部联系人
    elif choice == "4":
        if not contacts:
            print("📭 通讯录为空")
        else:
            print("\n" + "-" * 40)
            print(f"{'姓名':<10} {'电话号码':<15}")
            print("-" * 40)
            for name, phone in contacts.items():
                print(f"{name:<10} {phone:<15}")
            print("-" * 40)
            print(f"共 {len(contacts)} 位联系人")
    
    # 5. 退出系统
    elif choice == "5":
        print("👋 感谢使用通讯录系统！再见！")
        break
    
    # 无效输入
    else:
        print("❌ 无效选择，请重新输入 (1-5)")

